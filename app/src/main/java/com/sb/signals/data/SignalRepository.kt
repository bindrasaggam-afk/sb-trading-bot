    fun applyEvaluation(
        before: ResearchSignal,
        after: ResearchSignal,
        eventPrice: Double? = null
    ): Boolean = withDbOperation {
        val db = database.writableDatabase
        db.beginTransaction()
        try {
            val values = ContentValues().apply {
                put("status", after.status.name)
                put("triggered_at", after.triggeredAt)
                put("target1_at", after.target1At)
                put("target2_at", after.target2At)
                put("target3_at", after.target3At)
                put("stopped_at", after.stoppedAt)
                put("closed_at", after.closedAt)
                put("entry_fill_price", after.entryFillPrice)
                put("exit_price", after.exitPrice)
                put("outcome_r", after.outcomeR)
                put("outcome_pnl_percent", after.outcomePnlPercent)
                put("outcome_net_pnl_percent", after.outcomeNetPnlPercent)
                put("outcome_cost_percent", after.outcomeCostPercent)
                put("outcome_reason", after.outcomeReason)
                put("ambiguous_bar", if (after.ambiguousBar) 1 else 0)
                put(
                    "mfe_percent",
                    after.maxFavorableExcursionPercent
                )
                put(
                    "mae_percent",
                    after.maxAdverseExcursionPercent
                )
                put("last_evaluated_at", after.lastEvaluatedAt)
                put("evaluation_version", after.evaluationVersion)
            }
            val updated = db.update(
                SignalMigrations.TABLE_SIGNALS,
                values,
                "id = ?",
                arrayOf(before.id.toString())
            )
            if (updated > 0) {
                appendTransitions(db, before, after, eventPrice)
            }
            db.setTransactionSuccessful()
            updated > 0
        } finally {
            db.endTransaction()
        }
    }

    fun saveStrategyVersion(
        config: StrategyConfig,
        notes: String = ""
    ): Boolean = withDbOperation {
        val configJson = SignalJson.encodeConfig(config)
        val existing = versionConfig(config.strategyId, config.version)
        if (existing != null) {
            return@withDbOperation SignalStrategyVersionPolicy.canSave(existing, config)
        }

        val values = ContentValues().apply {
            put("strategy_id", config.strategyId)
            put("version", config.version)
            put("category", config.category.name)
            put("name", config.name)
            put("config_json", configJson)
            put("created_at", System.currentTimeMillis())
            put("active", 1)
            put("notes", notes)
        }
        val inserted = database.writableDatabase.insertWithOnConflict(
            SignalMigrations.TABLE_VERSIONS,
            null,
            values,
            SQLiteDatabase.CONFLICT_IGNORE
        )
        if (inserted != -1L) {
            true
        } else {
            val raced = versionConfig(config.strategyId, config.version)
            raced != null &&
                SignalStrategyVersionPolicy.canSave(raced, config)
        }
    }

    private fun versionConfig(
        strategyId: String,
        version: String
    ): String? {
        database.readableDatabase.query(
            SignalMigrations.TABLE_VERSIONS,
            arrayOf("config_json"),
            "strategy_id = ? AND version = ?",
            arrayOf(strategyId, version),
            null,
            null,
            null,
            "1"
        ).use { cursor ->
            return if (cursor.moveToFirst()) {
                cursor.getString(cursor.getColumnIndexOrThrow("config_json"))
            } else {
                null
            }
        }
    }

