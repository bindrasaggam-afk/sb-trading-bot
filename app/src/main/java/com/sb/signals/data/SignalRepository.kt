    fun query(filter: SignalFilter): List<ResearchSignal> = withDbOperation {
        val clauses = ArrayList<String>()
        val args = ArrayList<String>()

        filter.category?.let {
            clauses.add("category = ?")
            args.add(it.name)
        }
        if (filter.statuses.isNotEmpty()) {
            clauses.add(
                "status IN (${filter.statuses.joinToString(",") { "?" }})"
            )
            filter.statuses.forEach { args.add(it.name) }
        }
        filter.direction?.let {
            clauses.add("direction = ?")
            args.add(it.name)
        }
        filter.holdingGroup?.let { group ->
            if (group != HoldingFilterGroup.ALL) {
                val periods = HoldingPeriod.values()
                    .filter { it.filterGroup == group }
                    .map { it.name }
                clauses.add(
                    "holding_period IN (${periods.joinToString(",") { "?" }})"
                )
                args.addAll(periods)
            }
        }
        val query = filter.symbolQuery.trim()
        if (query.isNotEmpty()) {
            clauses.add("(symbol LIKE ? OR exchange LIKE ?)")
            val like = "%${query.uppercase()}%"
            args.add(like)
            args.add(like)
        }
        filter.fromTimestamp?.let {
            clauses.add("generated_at >= ?")
            args.add(it.toString())
        }
        filter.toTimestamp?.let {
            clauses.add("generated_at <= ?")
            args.add(it.toString())
        }

        val selection = clauses.joinToString(" AND ")
            .takeIf { it.isNotBlank() }
        queryInternal(
            selection = selection,
            selectionArgs = args.toTypedArray(),
            limit = filter.limit.coerceIn(1, 1000)
        )
    }

