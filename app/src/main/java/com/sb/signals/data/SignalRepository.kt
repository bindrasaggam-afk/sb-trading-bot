    private val lock = Any()
    private val operationGuard = DatabaseOperationGuard()

    private inline fun <T> withDbOperation(crossinline block: () -> T): T =
        operationGuard.withOperation { synchronized(lock) { block() } }

    fun insert(signal: ResearchSignal): Long = withDbOperation {
        val db = database.writableDatabase
        var insertedId = 0L
        db.beginTransaction()
        try {
            insertedId = db.insertWithOnConflict(
                SignalMigrations.TABLE_SIGNALS,
                null,
                signalValues(signal),
                SQLiteDatabase.CONFLICT_IGNORE
            )
            if (insertedId > 0L) {
                insertEventInternal(
                    db = db,
                    event = SignalEvent(
                        signalId = insertedId,
                        fromStatus = null,
                        toStatus = SignalLifecycleStatus.NEW,
                        eventTime = signal.generatedAt,
                        price = signal.referencePrice,
                        message = "Signal generated by ${signal.strategyId} " +
                            "v${signal.strategyVersion}"
                    )
                )
                try {
                    ResearchSnapshotWriter.capture(
                        db = db,
                        signalId = insertedId,
                        signal = signal
                    )
                } catch (error: Exception) {
                    // The original signal row already contains the exact
                    // snapshot JSON. Never fail signal generation because
                    // the analytics projection could not be written.
                    Log.e(
                        "SignalRepository",
                        "Research analytics snapshot capture failed",
                        error
                    )
                }
            }
            db.setTransactionSuccessful()
        } finally {
            db.endTransaction()
        }
        insertedId
    }

    fun getById(id: Long): ResearchSignal? = withDbOperation {
        database.readableDatabase.query(
            SignalMigrations.TABLE_SIGNALS,
            null,
            "id = ?",
            arrayOf(id.toString()),
            null,
            null,
            null,
            "1"
        ).use { cursor ->
            if (cursor.moveToFirst()) readSignal(cursor) else null
        }
    }

    fun getOpenSignals(category: SignalCategory? = null): List<ResearchSignal> =
        withDbOperation {
            val clauses = ArrayList<String>()
            val args = ArrayList<String>()
            clauses.add(openStatusClause())
            if (category != null) {
                clauses.add("category = ?")
                args.add(category.name)
            }
            queryInternal(
                selection = clauses.joinToString(" AND "),
                selectionArgs = args.toTypedArray(),
                limit = 5000
            )
        }

