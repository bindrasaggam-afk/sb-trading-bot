            entryHigh = cursor.getDouble(
                cursor.getColumnIndexOrThrow("entry_high")
            ),
            stopLoss = cursor.getDouble(
                cursor.getColumnIndexOrThrow("stop_loss")
            ),
            target1 = cursor.getDouble(
                cursor.getColumnIndexOrThrow("target1")
            ),
            target2 = cursor.getDouble(
                cursor.getColumnIndexOrThrow("target2")
            ),
            target3 = cursor.getDouble(
                cursor.getColumnIndexOrThrow("target3")
            ),
            riskPerUnit = cursor.getDouble(
                cursor.getColumnIndexOrThrow("risk_per_unit")
