    private fun appendTransitions(
        db: SQLiteDatabase,
        before: ResearchSignal,
        after: ResearchSignal,
        eventPrice: Double?
    ) {
        if (after.triggeredAt != null && before.triggeredAt == null) {
            insertEventInternal(
                db,
                SignalEvent(
                    signalId = after.id,
                    fromStatus = before.status,
                    toStatus = SignalLifecycleStatus.TRIGGERED,
                    eventTime = after.triggeredAt,
                    price = after.entryFillPrice ?: after.referencePrice,
                    message = "Entry filled"
                )
            )
        }
        if (after.target1At != null && before.target1At == null) {
            insertEventInternal(
                db,
                SignalEvent(
                    signalId = after.id,
                    fromStatus = SignalLifecycleStatus.TRIGGERED,
                    toStatus = SignalLifecycleStatus.TARGET_1_HIT,
                    eventTime = after.target1At,
                    price = after.target1,
                    message = "Target 1 reached"
                )
            )
        }
        if (after.target2At != null && before.target2At == null) {
            insertEventInternal(
                db,
                SignalEvent(
                    signalId = after.id,
                    fromStatus = SignalLifecycleStatus.TARGET_1_HIT,
                    toStatus = SignalLifecycleStatus.TARGET_2_HIT,
                    eventTime = after.target2At,
                    price = after.target2,
                    message = "Target 2 reached"
                )
            )
        }
        if (after.target3At != null && before.target3At == null) {
            insertEventInternal(
                db,
                SignalEvent(
                    signalId = after.id,
                    fromStatus = SignalLifecycleStatus.TARGET_2_HIT,
                    toStatus = SignalLifecycleStatus.TARGET_3_HIT,
                    eventTime = after.target3At,
                    price = after.target3,
                    message = "Target 3 reached"
                )
            )
        }
        if (after.stoppedAt != null && before.stoppedAt == null) {
            insertEventInternal(
                db,
                SignalEvent(
                    signalId = after.id,
                    fromStatus = before.status,
                    toStatus = SignalLifecycleStatus.STOPLOSS_HIT,
                    eventTime = after.stoppedAt,
                    price = after.exitPrice,
                    message = after.outcomeReason ?: "Stop-loss reached"
                )
            )
        }
        val finalStatus = after.status
        if (finalStatus != before.status &&
            finalStatus in setOf(
                SignalLifecycleStatus.EXPIRED,
                SignalLifecycleStatus.INVALIDATED,
                SignalLifecycleStatus.CLOSED,
                SignalLifecycleStatus.ACTIVE
            )
        ) {
            insertEventInternal(
                db,
                SignalEvent(
                    signalId = after.id,
                    fromStatus = before.status,
                    toStatus = finalStatus,
                    eventTime = after.closedAt
                        ?: after.lastEvaluatedAt
                        ?: after.generatedAt,
                    price = eventPrice ?: after.exitPrice,
                    message = after.outcomeReason
                        ?: finalStatus.label
                )
            )
        }
    }

    private fun insertEventInternal(
        db: SQLiteDatabase,
        event: SignalEvent
    ) {
        val values = ContentValues().apply {
            put("signal_id", event.signalId)
            put("from_status", event.fromStatus?.name)
            put("to_status", event.toStatus.name)
            put("event_time", event.eventTime)
            put("price", event.price)
            put("message", event.message)
        }
        db.insert(SignalMigrations.TABLE_EVENTS, null, values)
    }

    private fun openStatusClause(): String {
        val names = SignalLifecycleStatus.values()
            .filter { it.isOpen }
            .joinToString(",") { "'${it.name}'" }
        return "status IN ($names)"
    }

    private fun completedStatusClause(): String {
        val names = SignalLifecycleStatus.values()
            .filter { it.isCompleted }
            .joinToString(",") { "'${it.name}'" }
        return "status IN ($names)"
    }

    private fun Cursor.getStringOrNull(column: String): String? {
        val index = getColumnIndexOrThrow(column)
        return if (isNull(index)) null else getString(index)
    }

    private fun Cursor.getLongOrNull(column: String): Long? {
        val index = getColumnIndexOrThrow(column)
        return if (isNull(index)) null else getLong(index)
    }

    private fun Cursor.getDoubleOrNull(column: String): Double? {
        val index = getColumnIndexOrThrow(column)
        return if (isNull(index)) null else getDouble(index)
    }
