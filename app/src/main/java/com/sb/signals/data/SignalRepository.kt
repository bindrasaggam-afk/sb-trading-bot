                cursor.getString(cursor.getColumnIndexOrThrow("direction"))
            ) ?: SignalDirection.BUY,
            timeframe = cursor.getString(
                cursor.getColumnIndexOrThrow("timeframe")
            ),
            strategyId = cursor.getString(
                cursor.getColumnIndexOrThrow("strategy_id")
            ),
            strategyVersion = cursor.getString(
                cursor.getColumnIndexOrThrow("strategy_version")
            ),
            strategyConfigJson = cursor.getStringOrNull(
                "strategy_config_json"
            ).orEmpty(),
            candleTimestamp = cursor.getLong(
                cursor.getColumnIndexOrThrow("candle_timestamp")
            ),
            generatedAt = cursor.getLong(
                cursor.getColumnIndexOrThrow("generated_at")
            ),
            referencePrice = cursor.getDouble(
                cursor.getColumnIndexOrThrow("reference_price")
            ),
            entryLow = cursor.getDouble(
                cursor.getColumnIndexOrThrow("entry_low")
